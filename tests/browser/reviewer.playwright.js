// Run the generated node_modules/.cache/biai-reviewer/browser-run.js with Playwright MCP.
// Tests a production build with real HTTPS session endpoints and mocked server-side Gemini.
async (page) => {
  const password = /* TEST_PASSWORD */ null
  const browser = page.context().browser()
  const context = await browser.newContext({ ignoreHTTPSErrors: true })
  const testPage = await context.newPage()
  const passed = [], errors = [], failedAssets = []
  let unexpectedProvider = 0
  const check = (value, label) => { if (!value) throw new Error(label); passed.push(label) }
  const base = 'https://localhost:5180'
  const shot = name => testPage.screenshot({ path: `D:/BIAI/app/artifacts/task-008/${name}.png`, fullPage: true })
  testPage.on('pageerror', error => errors.push(error.message))
  testPage.on('requestfailed', request => { if (!request.url().includes('/api/')) failedAssets.push(request.url()) })
  await context.route('https://generativelanguage.googleapis.com/**', route => { unexpectedProvider++; return route.abort() })
  try {
    for (const [width, height] of [[1366, 768], [390, 844]]) {
      await context.clearCookies()
      await testPage.setViewportSize({ width, height })
      await testPage.goto(base)
      await testPage.getByRole('button', { name: 'Reviewer sign in', exact: true }).waitFor({ state: 'visible' })
      await testPage.getByRole('button', { name: 'AI Follow-up', exact: true }).click()
      await testPage.getByLabel('Select a lead').selectOption('L04')
      check(await testPage.getByRole('button', { name: 'Generate Draft', exact: true }).isDisabled(), `${width}: logged-out email locked`)
      await testPage.getByRole('button', { name: 'Ask Your Pipeline', exact: true }).click()
      await testPage.getByLabel('Your question', { exact: true }).fill('How many leads need a follow-up before November 1, 2026?')
      check(await testPage.getByRole('button', { name: 'Ask', exact: true }).isDisabled(), `${width}: logged-out query locked`)
      const unauthorized = await testPage.evaluate(async () => Promise.all(['draft', 'query'].map(async type => (await fetch(`/api/ai/${type}`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(type === 'draft' ? { leadId: 'L04' } : { question: 'Count overdue leads' }) })).status)))
      check(unauthorized.every(status => status === 401), `${width}: both actual endpoints reject logged-out requests`)
      await testPage.getByRole('button', { name: 'Reviewer sign in', exact: true }).click()
      await testPage.getByLabel('Reviewer password', { exact: true }).focus()
      check(await testPage.getByLabel('Reviewer password', { exact: true }).evaluate(el => el === document.activeElement && getComputedStyle(el).outlineStyle !== 'none'), `${width}: visible keyboard focus`)
      await shot(`${width}-logged-out`)
      if (width === 1366) {
        await testPage.getByLabel('Reviewer password', { exact: true }).fill('invalid test input')
        await testPage.getByRole('button', { name: 'Sign in', exact: true }).click()
        await testPage.getByRole('alert').filter({ hasText: 'not accepted' }).waitFor()
        check(await testPage.getByLabel('Reviewer password', { exact: true }).inputValue() === '', 'Invalid login clears password and announces failure')
        await shot('desktop-invalid-login')
      }
      await testPage.getByLabel('Reviewer password', { exact: true }).fill(password)
      await testPage.getByRole('button', { name: 'Sign in', exact: true }).click()
      await testPage.getByRole('button', { name: 'Sign out', exact: true }).waitFor()
      const cookie = (await context.cookies()).find(item => item.name === '__Host-biai-reviewer')
      check(cookie?.httpOnly && cookie.secure && cookie.sameSite === 'Strict' && cookie.path === '/', `${width}: real HttpOnly Secure Strict cookie installed`)
      check(!(await testPage.evaluate(() => document.cookie)).includes('__Host-biai-reviewer'), `${width}: JavaScript cannot read session cookie`)
      await testPage.reload()
      await testPage.getByRole('button', { name: 'Sign out', exact: true }).waitFor()
      check(await testPage.getByText('Reviewer signed in', { exact: true }).isVisible(), `${width}: server-confirmed session survives reload`)
      await testPage.getByRole('button', { name: 'AI Follow-up', exact: true }).click()
      await testPage.getByLabel('Select a lead').selectOption('L04')
      await testPage.getByRole('button', { name: 'Generate Draft', exact: true }).click()
      check(await testPage.getByRole('button', { name: 'Generating draft…', exact: true }).isDisabled(), `${width}: duplicate email submissions blocked`)
      await testPage.getByLabel('Subject', { exact: true }).waitFor()
      check((await testPage.getByLabel('Subject', { exact: true }).inputValue()).includes('Offline test'), `${width}: authenticated draft reaches mocked handler`)
      await testPage.getByLabel('Subject', { exact: true }).fill('Reviewer-edited subject')
      check(await testPage.getByLabel('Subject', { exact: true }).inputValue() === 'Reviewer-edited subject', `${width}: email remains editable`)
      await shot(`${width}-authenticated-draft`)
      await testPage.getByRole('button', { name: 'Ask Your Pipeline', exact: true }).click()
      await testPage.getByLabel('Your question', { exact: true }).fill('How many leads need a follow-up before November 1, 2026?')
      await testPage.getByRole('button', { name: 'Ask', exact: true }).click()
      check(await testPage.getByRole('button', { name: 'Interpreting…', exact: true }).isDisabled(), `${width}: duplicate query submissions blocked`)
      await testPage.getByRole('region', { name: 'Question result' }).waitFor()
      check((await testPage.getByRole('region', { name: 'Question result' }).innerText()).includes('9'), `${width}: authenticated query returns deterministic count`)
      check((await testPage.getByRole('region', { name: 'Question result' }).innerText()).includes('L25'), `${width}: query source IDs remain visible`)
      check(await testPage.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth), `${width}: no horizontal overflow`)
      await shot(`${width}-authenticated-query`)
      await testPage.getByRole('button', { name: 'Lead register', exact: true }).click()
      check(await testPage.locator('.lead-row').count() === 25, `${width}: all original records remain visible`)
      await testPage.getByLabel('Search company or contact').fill('Tanvir')
      check(await testPage.locator('.lead-row').count() === 1, `${width}: register search retained`)
      await testPage.getByRole('button', { name: 'Data health', exact: true }).click()
      check((await testPage.locator('main').innerText()).includes('10'), `${width}: Data Health remains available`)
      await testPage.getByRole('button', { name: 'Sign out', exact: true }).click()
      await testPage.getByText('Signed out. AI access is locked.', { exact: true }).waitFor()
      check(!(await context.cookies()).some(item => item.name === '__Host-biai-reviewer'), `${width}: logout removes actual cookie`)
      await testPage.getByRole('button', { name: 'AI Follow-up', exact: true }).click()
      await testPage.getByLabel('Select a lead').selectOption('L04')
      check(await testPage.getByRole('button', { name: 'Generate Draft', exact: true }).isDisabled(), `${width}: logout relocks email and clears prior workspace`)
      check(await testPage.getByLabel('Subject', { exact: true }).count() === 0, `${width}: previous draft cleared on logout`)
      await testPage.getByRole('button', { name: 'Ask Your Pipeline', exact: true }).click()
      await testPage.getByLabel('Your question', { exact: true }).fill('Count leads')
      check(await testPage.getByRole('button', { name: 'Ask', exact: true }).isDisabled(), `${width}: logout relocks queries`)
      check(await testPage.getByRole('region', { name: 'Question result' }).count() === 0, `${width}: previous query cleared on logout`)
      await shot(`${width}-signed-out`)
    }
    const counts = await testPage.evaluate(async () => (await fetch('/__test/metrics')).json())
    check(counts.draft === 2 && counts.query === 2 && counts.liveProviderRequests === 0 && unexpectedProvider === 0, 'Exactly two mocked draft and query calls, zero live provider calls')
    check(errors.length === 0, 'No uncaught browser errors')
    check(failedAssets.length === 0, 'No failed asset requests')
    return { passed, counts, screenshots: 'D:/BIAI/app/artifacts/task-008', errors, failedAssets }
  } finally { await context.close() }
}
